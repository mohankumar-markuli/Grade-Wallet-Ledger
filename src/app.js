const express=require('express');
const authRoutes=require('./routes/auth.routes');
const userRoutes=require('./routes/user.routes');
const userWalletRoutes=require('./routes/user-wallet.routes');
const walletRoutes=require('./routes/wallet.routes');
const transferRoutes=require('./routes/transfer.routes');
const statementRoutes=require('./routes/statement.routes');
const adminRoutes=require('./routes/admin.routes');
const app=express();
app.use(express.json({limit:'32kb'}));
app.use('/auth',authRoutes);
app.get('/api/health',(req,res)=>res.status(200).json({status:'ok',service:'grade-wallet-ledger'}));
app.use('/users',userRoutes);
app.use('/users',userWalletRoutes);
app.use('/wallets',walletRoutes);
app.use('/',statementRoutes);
app.use('/transfers',transferRoutes);
app.use('/admin',adminRoutes);
app.use((req,res)=>res.status(404).json({error:{code:'NOT_FOUND',message:'The requested resource was not found.'}}));
app.use((err,req,res,next)=>{
    if(res.headersSent) return next(err);
    const status=Number.isInteger(err.status)&&err.status>=400&&err.status<=599?err.status:500;
    const code=err.code||'INTERNAL_ERROR';
    const message=status===500?'The request could not be completed.':err.message;
    return res.status(status).json({error:{code,message}});
});
module.exports=app;
